#include <demos.h>
#include <stdint.h>
#include <string.h>

/* Use only the installed header and the library a release user receives. */
int main(void)
{
    const uint8_t message[] = {'a', 'b', 'c'};
    const uint8_t expected[64] = {
        0xdd,0xaf,0x35,0xa1,0x93,0x61,0x7a,0xba,0xcc,0x41,0x73,0x49,0xae,0x20,0x41,0x31,
        0x12,0xe6,0xfa,0x4e,0x89,0xa9,0x7e,0xa2,0x0a,0x9e,0xee,0xe6,0x4b,0x55,0xd3,0x9a,
        0x21,0x92,0x99,0x2a,0x27,0x4f,0xc1,0xa8,0x36,0xba,0x3c,0x23,0xa3,0xfe,0xeb,0xbd,
        0x45,0x4d,0x44,0x23,0x64,0x3c,0xe8,0x0e,0x2a,0x9a,0xc9,0x4f,0xa5,0x4c,0xa4,0x9f,
    };
    uint8_t digest[64], public_key[32], secret_key[64], signature[64];
    if (sha512(sizeof message, message, digest) != 0 || memcmp(digest, expected, sizeof digest) != 0) return 1;
    if (keypair(public_key, secret_key) != 0) return 2;
    if (sign(sizeof message, message, secret_key, signature) != 0) return 3;
    if (verify(sizeof message, message, public_key, signature) != 0) return 4;
    signature[0] ^= 1;
    return verify(sizeof message, message, public_key, signature) == 0 ? 5 : 0;
}
